        var mode = "login",
          dlg = $("#authDlg");
        function session() {
          if (typeof window.getCurrentUser === "function") {
            var u = window.getCurrentUser();
            if (u) {
              var r = u.role || (Array.isArray(u.roles) && u.roles[0]) || "patient";
              return {
                name: u.fullName || u.email,
                role: r.toLowerCase()
              };
            }
          }
          try {
            var raw = localStorage.getItem("medicareCurrentUser");
            if (raw) {
              var parsed = JSON.parse(raw);
              var role = parsed.role || (Array.isArray(parsed.roles) && parsed.roles[0]) || "patient";
              return {
                name: parsed.fullName || parsed.email,
                role: role.toLowerCase()
              };
            }
          } catch (e) {}
          return load("medicareSession", null);
        }
        function renderUser() {
          var s = session();
          $("#userBox").hidden = !s;
          $("#authBtn").hidden = !!s;
          if (s)
            $("#userName").textContent =
              t("hi") + " " + s.name + " (" + t("auth." + s.role) + ")";
        }
        function setMode(m) {
          mode = m;
          var reg = m === "reg";
          $("#tabLogin").setAttribute("aria-pressed", !reg);
          $("#tabReg").setAttribute("aria-pressed", reg);
          $("#fName").hidden = !reg;
          $("#fPhoneF").hidden = !reg;
          var doc = reg && $("#aRole").value === "doctor";
          $("#docFields").hidden = !doc;
          $("#docFields").style.display = doc ? "grid" : "none";
          $("#authSubmit").textContent = t(reg ? "auth.reg" : "auth.login");
          $("#aPass").autocomplete = reg ? "new-password" : "current-password";
        }
        function msg(txt, ok) {
          var m = $("#authMsg");
          m.hidden = !txt;
          m.className = "msg " + (ok ? "s" : "e");
          m.textContent = txt || "";
        }
